/** Native bounded snapshot upload/resume and complete restore; no private cache fingerprint crosses HTTP [H15,H17]. */
import { Refused } from './refused.js';
import { createRelayPageCache, snapshotSourceId } from './relay-page-cache.js';
import { openPagedSnapshot, writePagedSnapshot } from './relay-page-layout.js';
import { PAGE_CIPHER_BYTES, pageReference } from './sealed-pages.js';

const PAGE_CAPABILITIES = new WeakMap();

/** Refuse a malformed ACK instead of clearing the durable native pending snapshot. */
function invalid() { return new Refused('RELAY_RESPONSE', 'The relay did not acknowledge this sealed snapshot page. Retry the saved upload with the configured relay.'); }

/** Decode only bounded canonical cipher bytes received under a content-addressed object id. */
function bytes(value) {
  if (typeof value !== 'string' || value.length > 600_000 || !/^[A-Za-z0-9_-]+$/u.test(value)) throw invalid();
  const decoded = Buffer.from(value, 'base64url');
  if (!decoded.byteLength || decoded.byteLength > PAGE_CIPHER_BYTES || decoded.toString('base64url') !== value) throw invalid();
  return Uint8Array.from(decoded);
}

/** Keep account quota status only after validating its credential-free response fields. */
export function relayStorage(value) {
  if (!value || typeof value.account?.id !== 'string' || typeof value.account?.login !== 'string' ||
      !/^[A-Za-z0-9_-]{1,100}$/u.test(value.account.id) || !/^[A-Za-z0-9_-]{1,100}$/u.test(value.account.login) ||
      !Number.isSafeInteger(value.usedBytes) || value.usedBytes < 0 || !Number.isSafeInteger(value.limitBytes) || value.limitBytes < 1) return null;
  return { account: { id: value.account.id, login: value.account.login }, usedBytes: value.usedBytes, limitBytes: value.limitBytes };
}

/** Print account, used bytes and the operator-set limit without importing server-only quota storage into the CLI. */
export function relayStorageLine(value) {
  const storage = relayStorage(value);
  return storage ? `relay storage: account ${storage.account.login}, ${(storage.usedBytes / 1_000_000).toFixed(1)} MB used of ${(storage.limitBytes / 1_000_000).toFixed(1)} MB` : '';
}

/** Adapt the old internal pending-record interface only after the new protocol has proved an exact root ACK. */
export async function pagedSnapshotRequest(state, options, { request, key, decode, encode, maxEngine }) {
  const path = '/api/v2/boards/' + state.board;
  /** Retain the server-derived account totals from successful writes and reads. */
  function storage(value) { const result = relayStorage(value); if (result) state.storage = result; }
  if ((options.method ?? 'GET') === 'GET') {
    const document = await request(path + '/state', options);
    storage(document.state?.storage);
    const saved = document.state;
    if (document.apiVersion !== 2 || !saved || !Number.isSafeInteger(saved.sequence) || saved.sequence < 0) throw invalid();
    if (saved.apiVersion === 1) return { ...document, state: saved };
    if (saved.apiVersion !== 2 || !/^[A-Za-z0-9-]{1,128}$/u.test(saved.read?.id ?? '')) throw invalid();
    const root = pageReference(saved.root);
    if (root.sequence !== saved.sequence) throw invalid();
    const context = {
      key, boardId: state.board, sequence: saved.sequence,
      /** The server checks this path against the principal's pinned root on every request. */
      async get(id, parents) {
        const result = await request(path + '/objects/' + id + '?pin=' + encodeURIComponent(saved.read.id) + '&via=' + parents.join(','));
        if (result.apiVersion !== 2 || result.page?.id !== id) throw invalid();
        return bytes(result.page.sealed);
      },
    };
    const page = await openPagedSnapshot(root, context, { maxEngine });
    const native = await page.native();
    // Local resealing adapts existing restore callers, not the wire protocol. The authenticated root, cursor and
    // sender remain in the response; no locally generated bytes are reported as a server ciphertext ACK.
    let sealed = await encode(native, saved.sequence);
    const cache = createRelayPageCache(state);
    try {
      for (const pending of [state.snapshot, state.checkpoint]) if (pending?.sequence === saved.sequence && typeof pending.sealed === 'string') {
        const prepared = cache.job(snapshotSourceId(pending.sealed));
        if (prepared?.reference.id === root.id) { sealed = pending.sealed; break; }
      }
    } finally { cache.close(); }
    return { ...document, state: { ...saved, sealed } };
  }
  if (options.method !== 'PUT' || !Number.isSafeInteger(options.body?.sequence) || typeof options.body.sealed !== 'string') throw invalid();
  const pending = options.body;
  const source = snapshotSourceId(pending.sealed);
  const cache = createRelayPageCache(state);
  try {
    let prepared = cache.job(source);
    if (!prepared) {
      const native = await decode(pending);
      const context = { key, boardId: state.board, sequence: pending.sequence, put: cache.put, remember: cache.remember };
      context.lookup = fingerprint => cache.lookup(fingerprint, context);
      const reference = await writePagedSnapshot(native, context);
      cache.prepare(source, reference);
      prepared = cache.job(source);
    }
    if (prepared.reference.sequence !== pending.sequence) throw invalid();
    /** Resume only the same authenticated principal's live upload, otherwise start a new bounded session. */
    async function upload() {
      let result;
      try {
        result = await request(path + '/uploads', { method: 'POST', body: { sequence: pending.sequence, ...(prepared.upload ? { resume: prepared.upload } : {}) } });
      } catch (error) {
        if (error.code !== 'SNAPSHOT_UPLOAD_EXPIRED' || !prepared.upload) throw error;
        result = await request(path + '/uploads', { method: 'POST', body: { sequence: pending.sequence } });
      }
      storage(result.storage);
      if (result.apiVersion !== 2 || result.upload?.sequence !== pending.sequence || !/^[A-Za-z0-9-]{1,128}$/u.test(result.upload?.id ?? '')) throw invalid();
      cache.upload(source, result.upload.id);
      return result.upload.id;
    }
    let uploadId = await upload();
    const repaired = new Set();
    let renewed = false;
    for (;;) {
      try {
        for (const object of cache.pending(source)) {
          const result = await request(path + '/uploads/' + uploadId + '/objects/' + object.id, {
            method: 'PUT', body: { sequence: object.sequence, sealed: Buffer.from(object.bytes).toString('base64url'), children: object.children },
          });
          if (result.apiVersion !== 2 || result.page?.id !== object.id) throw invalid();
          cache.acknowledge(object.id);
        }
        const result = await request(path + '/uploads/' + uploadId + '/publish', {
          method: 'POST', body: { root: prepared.reference, ...(options.initialBaseline ? { initialOnly: true } : {}) },
        });
        const accepted = pageReference(result.state?.root);
        if (result.apiVersion !== 2 || result.state?.sequence !== pending.sequence || JSON.stringify(accepted) !== JSON.stringify(prepared.reference)) throw invalid();
        storage(result.state.storage);
        cache.complete(source);
        return { ...result, state: { ...result.state, sealed: pending.sealed } };
      } catch (error) {
        if (error.code === 'SNAPSHOT_UPLOAD_EXPIRED' && !renewed) {
          renewed = true; prepared.upload = uploadId; uploadId = await upload(); continue;
        }
        if (error.code !== 'SNAPSHOT_PAGE_MISSING' || !/^[0-9a-f]{64}$/u.test(error.page ?? '') || repaired.has(error.page)) throw error;
        repaired.add(error.page);
        cache.missing(error.page);
      }
    }
  } finally { cache.close(); }
}

/** Negotiate bounded snapshots only when needed; small legacy heads keep their existing wire interface. */
export async function relaySnapshotRequest(state, path, options = {}, io, hooks) {
  const snapshot = path === '/api/v1/boards/' + state.board + '/state' && ['GET', 'PUT'].includes(options.method ?? 'GET');
  /** Probe the configured relay once per command without downgrading a board already known to use pages. */
  async function supportsPages() {
    const owner = io && typeof io === 'object' ? io : state;
    let origins = PAGE_CAPABILITIES.get(owner);
    if (!origins) { origins = new Map(); PAGE_CAPABILITIES.set(owner, origins); }
    if (!origins.has(state.url)) origins.set(state.url, (async () => {
      try { return (await hooks.raw('/api/v2', {})).apiVersion === 2; }
      catch (error) { if (error.httpStatus === 404 && error.relayVersion === 1) return false; throw error; }
    })());
    const supported = await origins.get(state.url);
    if (!supported && state.snapshotApiVersion === 2) throw new Refused('RELAY_API_VERSION', 'This board requires relay API version 2. Upgrade the configured relay before syncing.');
    return supported;
  }
  /** Keep the old internal retry carrier, while only bounded sealed objects cross the new HTTP interface. */
  async function paged() {
    state.snapshotApiVersion = 2;
    const key = hooks.key();
    try {
      return await pagedSnapshotRequest(state, options, { key, maxEngine: hooks.maxEngine,
        request: hooks.raw,
        decode: record => hooks.decode(record, key),
        encode: (value, sequence) => hooks.encode(value, sequence, key),
      });
    } catch (error) {
      const storage = relayStorage(error.storage);
      if (storage) state.storage = storage;
      throw error;
    } finally {
      hooks.persist();
    }
  }
  const oversized = options.method === 'PUT' && typeof options.body?.sealed === 'string' && options.body.sealed.length > Math.floor(hooks.legacyLimit * 4 / 3);
  if (snapshot && (state.snapshotApiVersion === 2 || oversized) && await supportsPages()) return paged();
  try { return await hooks.raw(path, options); }
  catch (error) {
    if (!snapshot || error.code !== 'RELAY_API_VERSION' || !await supportsPages()) throw error;
    return paged();
  }
}
